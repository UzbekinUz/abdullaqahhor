// '/stories/s1' -> bitta hujjat; '/stories?x' -> ro'yxat; '/site' -> obyekt
export function demoFor(path) {
  const [p] = path.split('?')
  const [, key, id] = p.split('/')
  const map = { site: 'site', stories: 'stories', works: 'works', quotes: 'quotes', gallery: 'gallery', videos: 'videos', sources: 'sources' }
  const data = DEMO[map[key]]
  if (data === undefined) return null
  return id ? data.find((x) => x._id === id) ?? null : data
}
